const fs=require("node:fs");
const vm=require("node:vm");
const path=require("node:path");
const context=vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname,"../src/core.js"),"utf8"),context);
const passed=(function testCore(core) {
  const equal=(a,b,label)=>{if(JSON.stringify(a)!==JSON.stringify(b))throw new Error(label+": "+JSON.stringify(a));};
  equal(Array.from(core.matches("Yesterday yesterday TODAY","yesterday")),[{start:0,end:9},{start:10,end:19}],"case insensitive");
  equal(Array.from(core.matches("Yesterday yesterday","Yesterday",true)),[{start:0,end:9}],"case sensitive");
  equal(Array.from(core.matches("a.b aab [x]","a.b")),[{start:0,end:3}],"literal dot");
  equal(Array.from(core.matches("a.b aab [x]","[x]")),[{start:8,end:11}],"literal brackets");
  equal(Array.from(core.matches("abc","")),[],"empty");
  equal(Array.from(core.matches("🦊 Yesterday","Yesterday")),[{start:3,end:12}],"UTF16 offsets");
  equal(core.nextTop(100,200,1000),230,"overlap");
  equal(core.nextTop(990,200,1000),1000,"clamp");
  equal(core.nextTop(0,0,10),1,"minimum step");
  const idx=core.index(2), h={match:"Yesterday",context:"[Yesterday]",x:10,y:100};
  equal(idx.add(h),"added","first");
  equal(idx.add({...h,y:102}),"duplicate","jitter");
  equal(idx.add({...h,y:148}),"added","same text distinct row");
  equal(idx.add({...h,y:196}),"limit","bounded");
  equal(idx.items.length,2,"count");
  const p=core.index(), sticky={...h,pinnedKey:"node:0:Yesterday"};
  equal(p.add(sticky),"added","sticky first");
  equal(p.add({...sticky,y:500}),"duplicate","sticky moved");
  equal(p.add({...sticky,pinnedKey:"node:10:Yesterday"}),"added","different pinned occurrence");
  equal(p.add(h),"added","ordinary occurrence at same position");
  const anchored=core.index(), a={...h,anchorKey:"a"};
  equal(anchored.add(a),"added","anchor first");
  equal(anchored.add({...a,y:700}),"duplicate","anchor moves");
  equal(anchored.items[0].y,700,"anchor coordinate refreshed");
  equal(anchored.add({...a,anchorKey:"b"}),"added","different identity same text");
  const changing=core.index(), old={...h,anchorKey:"path-a",anchor:{attr:"data-item-id",value:"row"}};
  equal(changing.add(h),"added","unanchored observation");
  equal(changing.add(old),"duplicate","upgrade anchor");
  equal(changing.add({...old,anchorKey:"path-b"}),"duplicate","same record different path");
  equal(changing.items[0].anchorKey,"path-b","updated identity");
  equal(changing.add(h),"duplicate","retain anchor when temporarily absent");
  equal(changing.items[0].anchorKey,"path-b","retained anchor");
  equal(changing.add({...old,anchorKey:"different",anchor:{attr:"data-item-id",value:"other"}}),"added","different record at same coordinates");
  equal(changing.items.length,2,"count after reconciliation");
  return 30;
})(context.__vpfCore);
console.log(passed+" assertions passed");
